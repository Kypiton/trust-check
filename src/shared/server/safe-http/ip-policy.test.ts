import { describe, expect, it } from "vitest";
import { isPublicAddress } from "./ip-policy";

describe("public destination IP policy", () => {
  it.each([
    "0.0.0.0", "0.255.255.255", "10.0.0.1", "10.255.255.255",
    "100.64.0.1", "100.127.255.255", "127.0.0.1", "127.255.255.255",
    "169.254.169.254", "169.254.0.1", "172.16.0.1", "172.31.255.255", "192.168.1.1",
    "192.0.0.1", "192.0.0.170", "192.0.2.1", "192.88.99.1", "198.18.0.1", "198.19.255.255",
    "198.51.100.1", "203.0.113.1", "224.0.0.1", "239.255.255.255", "240.0.0.1", "255.255.255.255",
    "::", "::1", "::127.0.0.1", "fc00::1", "fdff:ffff::1", "fe80::1", "febf::1", "fec0::1", "ff02::1",
    "::ffff:127.0.0.1", "::ffff:7f00:1", "::ffff:10.0.0.1", "::ffff:169.254.169.254", "::ffff:192.0.2.1",
    "64:ff9b::7f00:1", "64:ff9b::a9fe:a9fe", "64:ff9b::808:808", "64:ff9b:1::a00:1",
    "100::1", "100:0:0:1::1", "2001::1", "2001:2::1", "2001:20::1", "2001:db8::1",
    "2002:7f00:1::", "2002:808:808::", "3ffe::1", "3fff::1", "3fff:fff::1", "5f00::1",
    "4000::1", "fe80::1%eth0", "2001:4860::1%eth0",
  ])("blocks %s", (address) => expect(isPublicAddress(address)).toBe(false));

  it.each([
    "8.8.8.8", "1.1.1.1", "93.184.216.34", "100.63.255.255", "100.128.0.0",
    "172.15.255.255", "172.32.0.0", "198.17.255.255", "198.20.0.0", "223.255.255.255",
    "2001:4860:4860::8888", "2606:4700:4700::1111", "2a00:1450::1", "::ffff:8.8.8.8",
  ])("allows ordinary public unicast %s", (address) => expect(isPublicAddress(address)).toBe(true));

  it.each(["", "hostname.com", "999.1.1.1", "127.1", "2130706433", "0x7f000001", "[::1]", "8.8.8.8/32"])(
    "rejects noncanonical/non-IP policy input: %s", (address) => expect(isPublicAddress(address)).toBe(false),
  );
});
